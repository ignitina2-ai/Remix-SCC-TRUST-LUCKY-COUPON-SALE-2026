// Utility to share or download the generated PNG image
export async function shareOrDownloadImage(dataUrl: string, fileName: string, title: string) {
  try {
    // Convert dataUrl to blob
    const res = await fetch(dataUrl);
    const blob = await res.blob();
    const file = new File([blob], `${fileName}.png`, { type: 'image/png' });

    // Try utilizing the original Web Share API if possible (especially for mobile versions)
    if (navigator.share && navigator.canShare && navigator.canShare({ files: [file] })) {
      await navigator.share({
        files: [file],
        title: title,
        text: `${title} - Generated by Coupon Sale Tracker`
      });
      return;
    }
  } catch (err) {
    console.warn("Native share failed, falling back to download:", err);
  }

  // Fallback to direct browser download
  const link = document.createElement('a');
  link.download = `${fileName}.png`;
  link.href = dataUrl;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

